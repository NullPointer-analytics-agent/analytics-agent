using SharedClasses;
using SharedClasses.ResponseDto;
using System.Net.Http.Json;
using System.Text.RegularExpressions;

string userPrompt = """
Наша система обрабатывает заказы. У каждого заказа есть три параметра состояния:
Стадия обработки (текстовое значение): может быть только одной из шести — «Новый», «Подтвержден», «Упакован», «Отправлен», «Доставлен» или «Отменен».
Признак оплаты (логическое значение): оплачен заказ или нет.
Тип доставки (целое число): может принимать только одно из трёх значений — 1 (стандартная), 2 (ускоренная) или 3 (премиальная).
Когда заказ только создаётся, он всегда имеет начальные параметры: стадия «Новый», признак оплаты «не оплачен», тип доставки установлен в 1.
Дальше с заказом могут происходить следующие события:
Подтверждение заказа. Доступно, пока заказ находится в стадии «Новый». При этом заказ переходит в стадию «Подтвержден».
Выбор ускоренной доставки. Доступно из стадий «Новый» и «Подтвержден». Тип доставки устанавливается равным 2.
Выбор премиальной доставки. Доступно из стадий «Новый» и «Подтвержден». Тип доставки устанавливается равным 3.
Оплата заказа. Доступна из стадии «Подтвержден». Статус оплаты меняется на «оплачен».
Упаковка заказа. Доступна из стадии «Подтвержден», но только если заказ уже оплачен. Заказ переходит в стадию «Упакован».
Отправка заказа. Доступна из стадии «Упакован». Заказ переходит в стадию «Отправлен».
Доставка заказа. Доступна из стадии «Отправлен». Заказ переходит в стадию «Доставлен».
Отмена заказа. Доступна из стадий «Новый» и «Подтвержден». Заказ переходит в стадию «Отменен».
Оформление повторного заказа. Доступно из стадии «Доставлен». Заказ полностью сбрасывается: стадия становится «Новый», статус оплаты становится «не оплачен», а тип доставки устанавливается равным 1.
Восстановление отмененного заказа. Доступно из стадии «Отменен». Заказ возвращается к началу: стадия становится «Новый», статус оплаты становится «не оплачен», а тип доставки устанавливается равным 1.
Что мы хотим гарантировать и проверить с помощью формальной верификации:
Гарантия оплаты при доставке: у заказа в стадии «Доставлен» признак оплаты всегда должен быть истинным. Доставленным не может оказаться заказ, который не был оплачен.
Невозможность доставки отмененного заказа: отмененный заказ ни при каких условиях не должен оказаться в стадии «Доставлен». Мы хотим убедиться, что из состояния «Отменен» нельзя попасть в «Доставлен» без полного сброса в «Новый».
Достижимость успешного сценария: нам важно знать, что путь «заказ подтвердили → оплатили → упаковали → отправили → доставили» в принципе возможен. То есть до стадии «Доставлен» существует хотя бы один корректный путь переходов.
Отсутствие тупиков: мы хотим быть уверены, что в системе нет состояний, из которых нельзя выйти. Из любого достижимого состояния всегда должно быть доступно совершить хотя бы одно действие.

""";



UserRequestDto body = new()
{
    Prompt = userPrompt
};


using HttpRequestMessage request = new()
{
    Method = HttpMethod.Post,
    RequestUri = new Uri("http://localhost:5155/api/chat"),
    Content = JsonContent.Create(body)
};

using HttpClient client = new();

using HttpResponseMessage response = await client.SendAsync(
    request,
    HttpCompletionOption.ResponseHeadersRead
);

using Stream stream = await response.Content.ReadAsStreamAsync();

using StreamReader reader = new(stream);

while (true)
{
    string? line = await reader.ReadLineAsync();
    if (line == null) break;


    ResponseDtoBase? responsePart = ResponseDtoBase.FromString(line);

    if(responsePart is ChunkDto chunk)
    {
        string text = Regex.Unescape(chunk.ChunkText);

        Console.Write(text);
    }
    else
        Console.WriteLine(responsePart?.SerializeMultiLine() ?? "Error: response part is null");
}
